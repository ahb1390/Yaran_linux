#!/bin/bash
set -eu
printf 'Yaran Linux 2.0 \\n \\l\n' > /etc/issue
printf 'Yaran Linux 2.0\n' > /etc/issue.net
mkdir -p /etc/default/grub.d
# GRUB_THEME is the standard Debian mechanism: /etc/grub.d/00_header loads the
# theme (background, fonts, menu layout) into the generated grub.cfg. It takes
# effect on the installed system, because Calamares' bootloader module runs
# `update-grub` inside the target after this file is in place.
# GRUB_BACKGROUND stays as a fallback for the case where the theme directory
# is removed; the graphical menu itself degrades to plain text automatically
# on hardware without usable graphics, and the recovery entries generated by
# update-grub remain available in the "Advanced options" submenu.
#
# GRUB_BACKGROUND MUST NOT contain whitespace. /etc/grub.d/05_debian_theme
# runs before 00_header, picks GRUB_BACKGROUND up whenever it is set and
# writes `background_image <path>` into grub.cfg WITHOUT quoting the path
# (make_system_path_relative_to_its_root). GRUB's parser then truncates the
# value at the first space and every boot fails with:
#   error: bitmap file "/usr/share/wallpapers/Yaran" is of unsupported format
# so the fallback points at the space-free copy that
# hooks/desktop/grub-theme.sh installs. The branded "Yaran Emblem" wallpaper
# itself stays where it is — its directory name contains a space and is only
# safe for shell-side consumers that quote the path.
cat > /etc/default/grub.d/50-yaran.cfg <<'EOF'
GRUB_DISTRIBUTOR="Yaran Linux 2.0"
GRUB_THEME="/usr/share/grub/themes/yaran/theme.txt"
GRUB_BACKGROUND="/usr/share/grub/themes/yaran/background.png"
GRUB_GFXMODE=auto
GRUB_GFXPAYLOAD_LINUX=keep
EOF
